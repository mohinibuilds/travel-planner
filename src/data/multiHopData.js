// CORE MULTI-HOP ALGORITHM
// ═══════════════════════════════════════════════════════════════════════════════
export const buildMultiHopRoutes = (from, to, passengers = 1) => {
  const routes = [];
  const fromHub = townToHub[from];
  const toHub   = townToHub[to];

  const LONG_DIST_COST  = { flight: 6.5, train: 1.2, bus: 1.8 };
  const LONG_DIST_SPEED = { flight: 800, train: 120, bus: 60 };

  const legCost = (mode, dist, pax) => {
    const cpp = Math.max(100, (localModeCost[mode] ?? LONG_DIST_COST[mode] ?? 2) * dist);
    return { costPerPerson: Math.round(cpp), total: Math.round(cpp * pax) };
  };

  // Route A: Direct (both major cities)
  if (!fromHub && !toHub) {
    ["flight","train","bus"].forEach(mode => {
      const dist = getHubDist(from, to) || 500;
      const speed = LONG_DIST_SPEED[mode];
      const cost = legCost(mode, dist, passengers);
      routes.push({
        id: `direct-${mode}`,
        label: "Direct",
        totalDuration: parseFloat((dist / speed).toFixed(1)),
        totalCost: cost.total,
        costPerPerson: cost.costPerPerson,
        legs: [{ from, to, mode, dist, duration: parseFloat((dist/speed).toFixed(1)),
          cost: cost.total, train: mode==="train"?"Express Train":undefined, layover: 0 }],
        transfers: 0,
        lowestCost: mode === "train" || mode === "bus"
      });
    });
    return routes;
  }

  // Route B: Small town → Hub → Destination
  const buildViaHub = (origin, destination, originHub, destHub) => {
    if (!originHub) return;
    const leg1Mode = originHub.modeToHub;
    const leg1Cost = legCost(leg1Mode, originHub.distToHub, passengers);

    ["train","bus","flight"].forEach(longMode => {
      if (destHub) {
        const hubDist = getHubDist(originHub.hub, destHub.hub) || 400;
        const hubSpeed = LONG_DIST_SPEED[longMode];
        const leg2Cost = legCost(longMode, hubDist, passengers);
        const leg3Cost = legCost(destHub.modeToHub, destHub.distToHub, passengers);
        const totalDur = originHub.timeToHub + 0.5 + (hubDist/hubSpeed) + 0.5 + destHub.timeToHub;
        const totalCost = leg1Cost.total + leg2Cost.total + leg3Cost.total;
        routes.push({
          id: `hop-${leg1Mode}-${longMode}-${destHub.modeToHub}`,
          label: `Via ${originHub.hub} + ${destHub.hub}`,
          totalDuration: parseFloat(totalDur.toFixed(1)),
          totalCost, costPerPerson: Math.round(totalCost/passengers),
          transfers: 2, lowestCost: longMode !== "flight",
          legs: [
            { from: origin, to: originHub.hub, mode: leg1Mode,
              dist: originHub.distToHub, duration: originHub.timeToHub,
              cost: leg1Cost.total, train: leg1Mode==="train"?"Passenger/Express Train":undefined, layover: 0.5 },
            { from: originHub.hub, to: destHub.hub, mode: longMode,
              dist: hubDist, duration: parseFloat((hubDist/hubSpeed).toFixed(1)),
              cost: leg2Cost.total, layover: 0.5 },
            { from: destHub.hub, to: destination, mode: destHub.modeToHub,
              dist: destHub.distToHub, duration: destHub.timeToHub,
              cost: leg3Cost.total, layover: 0 }
          ]
        });
      } else {
        const hubDist = getHubDist(originHub.hub, destination) || 400;
        const hubSpeed = LONG_DIST_SPEED[longMode];
        const leg2Cost = legCost(longMode, hubDist, passengers);
        const totalDur = originHub.timeToHub + 0.5 + (hubDist/hubSpeed);
        const totalCost = leg1Cost.total + leg2Cost.total;
        routes.push({
          id: `hop-${leg1Mode}-${longMode}`,
          label: `Via ${originHub.hub}`,
          totalDuration: parseFloat(totalDur.toFixed(1)),
          totalCost, costPerPerson: Math.round(totalCost/passengers),
          transfers: 1, lowestCost: longMode !== "flight",
          legs: [
            { from: origin, to: originHub.hub, mode: leg1Mode,
              dist: originHub.distToHub, duration: originHub.timeToHub,
              cost: leg1Cost.total, train: leg1Mode==="train"?"Jan Shatabdi/Passenger":undefined, layover: 0.5 },
            { from: originHub.hub, to: destination, mode: longMode,
              dist: hubDist, duration: parseFloat((hubDist/hubSpeed).toFixed(1)),
              cost: leg2Cost.total, train: longMode==="train"?"Express/Superfast":undefined, layover: 0 }
          ]
        });
      }
    });
  };

  buildViaHub(from, to, fromHub, toHub);

  // Route C: Alt junction routing
  if (fromHub && fromHub.hub !== "Manmad" && from.includes("Maharashtra") === false) {
    const altHub = fromHub.hub;
    const altDist = fromHub.distToHub + 30;
    const altCost = legCost("bus", altDist, passengers);
    const onwardDist = getHubDist(altHub, to) || 300;
    const onwardCost = legCost("train", onwardDist, passengers);
    if (routes.length < 4) {
      routes.push({
        id: "alt-junction",
        label: `Alt: Via ${altHub} Junction`,
        totalDuration: parseFloat((fromHub.timeToHub + 0.5 + onwardDist/120).toFixed(1)),
        totalCost: altCost.total + onwardCost.total,
        costPerPerson: Math.round((altCost.total + onwardCost.total)/passengers),
        transfers: 2, lowestCost: false, alternative: true,
        legs: [
          { from, to: altHub, mode: "bus", dist: altDist,
            duration: fromHub.timeToHub, cost: altCost.total, layover: 0.5 },
          { from: altHub, to, mode: "train", dist: onwardDist,
            duration: parseFloat((onwardDist/120).toFixed(1)),
            cost: onwardCost.total, train: "Jan Shatabdi Express", layover: 0 }
        ]
      });
    }
  }

  routes.sort((a, b) => a.totalCost - b.totalCost);
  return routes.slice(0, 4);
};

