// ── Lookup with fuzzy fallback ──────────────────────────────────────────────
export const getCityCoords = (city) => {
  if (!city) return null;

  // Direct
  if (cityCoords[city]) return cityCoords[city];

  // Case-insensitive
  const key = Object.keys(cityCoords).find(
    k => k.toLowerCase() === city.toLowerCase()
  );
  if (key) return cityCoords[key];

  // Partial (e.g. "New Delhi" → "Delhi", "Bengaluru" → "Bangalore")
  const partial = Object.keys(cityCoords).find(
    k => city.toLowerCase().includes(k.toLowerCase()) || k.toLowerCase().includes(city.toLowerCase())
  );
  if (partial) return cityCoords[partial];

  return null; // unknown city
};
